"""Render ``docs/LEGACY_AUDIT.md`` from ``results/legacy_audit/audit_numbers.json``.

Every number in the audit document is injected here from the computed JSON; the prose is fixed in this module.
The section on the legacy-protocol replication is appended by the M4 analysis (``replicate.py``), which writes
``results/legacy_audit/replication.json``; until that file exists the document says the replication is pending.
"""

from __future__ import annotations

import json

from nycemis.paths import docs_dir, rel, results_dir


def _pct(x: float) -> str:
    return f"{x:.1f}%"


def _int(x: int) -> str:
    return f"{x:,}"


def _hits(hits: list[dict]) -> str:
    return "; ".join(f"cell {h['cell']} line {h['line']}" for h in hits)


def _replication_section() -> str:
    path = results_dir() / "legacy_audit" / "replication.json"
    if not path.is_file():
        return (
            "## 5. Legacy-protocol replication (M4)\n\n"
            "Pending. Condition C5 (`legacy_ml`, docs/SPECIFICATION.md 7.4) runs in the M4 pilot under the matched protocol. "
            "It reports the legacy metric (sum of all records with unmatched horizons) next to the matched metric "
            "on the same seeds, the route-change rate of the legacy rule, and the triviality and leakage tests of "
            "the legacy prediction task. Rendering this document again after M4 fills this section from "
            "`results/legacy_audit/replication.json`.\n"
        )
    from nycemis.legacy.replicate import render_replication_section

    return render_replication_section(json.loads(path.read_text(encoding="utf-8")))


def render_audit(n: dict) -> str:
    d1, d2, d4, d5, d6, d7, d8 = (
        n["d1_horizon"],
        n["d2_reroutes"],
        n["d4_models"],
        n["d5_runs"],
        n["d6_threshold"],
        n["d7_hardcoded"],
        n["d8_references"],
    )
    rf, xgb = d2["rf"], d2["xgb"]
    lo, hi = d1["baseline_t_max_bounds_s"]
    drops = d1["reported_drops_pct"]
    drop_rf = " / ".join(f"{drops['RF'][p]:g}" for p in ("CO2", "CO", "NOx", "HC", "PMx"))
    drop_xgb = " / ".join(f"{drops['XGBoost'][p]:g}" for p in ("CO2", "CO", "NOx", "HC", "PMx"))
    mse = d4["model_compare_cell_18"]
    same_first, common = d2["first_route_identical_rf_vs_xgb"]
    files = n["files"]
    pages = n["pages"]
    d1_status, d2_status = "supported-indirect", "supported-indirect"
    rep_path = results_dir() / "legacy_audit" / "replication.json"
    if rep_path.is_file():
        from nycemis.legacy.replicate import d1_confirmed, mean_change_rate

        rep = json.loads(rep_path.read_text(encoding="utf-8"))
        d1_status = ("confirmed by the replication (section 5)" if d1_confirmed(rep)
                     else "not reproduced by the replication (section 5)")
        d2_status = (f"replication: {100 * mean_change_rate(rep):.1f}% of the legacy calls changed the route "
                     "(section 5)")

    inventory = "\n".join(
        f"| `{v['path']}` | `{v['sha256'][:16]}...` | {_int(v['bytes'])} | {pages.get(k, '-')} |"
        for k, v in files.items()
    )
    sample_rows = d7["sample_cell_4_rows"]
    veh0_rows = [k for k, v in sample_rows.items() if v[1] == "veh0"]

    text = f"""# Legacy audit

Generated by `python -m nycemis legacy-audit` from `results/legacy_audit/audit_numbers.json`, which is computed
directly from the files in `legacy/`. Do not edit this file by hand; the prose lives in
`src/nycemis/legacy/report.py`. Notebook cells are 0-based `.ipynb` indices (code in `legacy/notebook_code.py`,
text outputs in `legacy/notebook_outputs.txt`). Page numbers are PDF page indices; the report's printed page
numbers are one lower.

Status vocabulary: **confirmed** (the files show it), **refuted** (the files show the opposite),
**unverifiable** (the files cannot decide it), **supported-indirect** (the decisive file is missing, but every
available number is consistent with it; the legacy-protocol replication in M4 decides it with data).

## 1. Inputs

| File | SHA-256 | Bytes | PDF pages |
|---|---|---|---|
{inventory}

The report has {pages['ML_SUMO_ProjectReport.pdf']} pages and the slides {pages['SUMO_ML_Project.pdf']}, matching the
expected 48 and 31. The notebook has {n['notebook']['cells']} cells (nbformat {n['notebook']['nbformat']}).
No legacy SUMO files (`flushing.sumocfg`, `osm.net.xml`, route files, `emissions_data*.xml`) are available, so the
horizon of each emissions XML cannot be read directly.

## 2. Summary

| # | Legacy claim or suspected defect | Evidence | Status | How the new design addresses it |
|---|---|---|---|---|
| 1 | Rerouting reduced emissions by RF {drop_rf} % and XGBoost {drop_xgb} % (CO2 / CO / NOx / HC / PMx) | Slides p. 23; report pp. 35-36; computed in cell {50} by summing all rows of three emission files | unverifiable as an effect; explained by rows 2-3 | Matched protocol (P2), paired seeds, C0 reference, C5 replication |
| 2 | D1 unmatched horizon | Baseline spans {lo:,.0f}-{hi:,.0f} s; controlled runs stop at step {d1['controlled_step_bound']}; row ratios {_pct(100 * d1['rf_row_ratio'])} (RF), {_pct(100 * d1['xgb_row_ratio'])} (XGB) | {d1_status} | Run to completion with the same stopping rule for every condition (4.4) |
| 3 | D2 rerouting is a no-op | {_int(rf['repeat_unchanged'])} of {_int(rf['repeat_calls'])} repeat calls (RF) and {_int(xgb['repeat_unchanged'])} of {_int(xgb['repeat_calls'])} (XGB) returned the unchanged route | {d2_status} | Efforts set on every edge, `rerouteEffort`, measured `route_change_rate` (4.3, 4.5) |
| 4 | D3 no baselines or controls | Only `emissions_data.xml` plus one file per model are compared (cells 50-55) | confirmed | C0 static, C1 travel-time rerouting, C2 random-reroute placebo |
| 5 | D4 circular, leaky prediction task | NOx predicted from CO2, CO, HC, PMx of the same vehicle-step; random row split (cells 18, 30, 45) | confirmed | Traffic-only features forecasting the next 60 s, split by run (7.1-7.3) |
| 6 | D5 "multiple simulation runs" averaged (report p. {d5['multiple_runs_claim_pages'][0]}) | One baseline and one run per model; no seeds, no averaging code | unverifiable (no evidence in the notebook) | 30-60 paired seeds per condition with CIs (4.6-4.7) |
| 7 | D6 threshold 1.88 with no stated unit basis | Labelled "bpm", "ppm" in code and "g/mile" in the report and slides; compared with predicted per-vehicle NOx rate | confirmed | Legacy threshold re-expressed as a training-NOx quantile; literal 1.88 run in mg/s (7.4) |
| 8 | D7 placeholders, hard-coded paths, broken loop | {len(d7['replace_with_actual'])} "replace with actual" lines; {len(d7['hardcoded_drive_paths'])} `D:\\` paths; cell 2 loop never increments `step` | confirmed | Results-driven figures, relative paths, hygiene tests (P1, P6, 9.10) |
| 9 | D8 references | None of the four legacy references could be located; three cited locators resolve to unrelated papers | unverifiable (not reused) | Only primary-verified citations, logged in `docs/CITATION_LEDGER.md` |
| 10 | "All simulation parameters ... kept consistent across different runs" (report p. 30) | Horizons differ (row 2); the two controlled runs diverge ({_int(d1['rf_controlled_rows'])} vs {_int(d1['xgb_controlled_rows'])} rows; first routes identical for {same_first} of {common} vehicles) | refuted | Byte-identical route files and settings asserted by hash (4.4, 9.4) |
| 11 | Dataset of {_int(d1['baseline_rows_report'])} rows (report p. 14) | The notebook's parse of the same file gives {_int(d1['baseline_rows_notebook'])} rows | confirmed discrepancy | Every reported number generated from results files (P1) |
| 12 | Maps of "NOx levels as high as 12 units (µg/m³)" after rerouting (report p. 31) | Colour bars label predicted per-vehicle emission rates as µg/m³ ({_hits(d6['colorbar_concentration_labels'])}); the map cells 42 and 48 raised errors | confirmed | Emissions reported as mass totals with explicit units; no concentration claims (4.9) |

## 3. Details

### D1 Unmatched horizon (rows 1, 2)

- The baseline file `emissions_data.xml` has {_int(d1['baseline_rows_notebook'])} vehicle-step rows (cell 6 output).
- Its time span is not printed, but cell 12 min-max normalizes the Time column and prints it to six decimals.
  With Time = 0 in row 0, the printed values bound the last timestamp to {lo:,.1f}-{hi:,.1f} s.
- Both controlled runs loop `while traci.simulation.getMinExpectedNumber() > 0 and step < {d1['controlled_step_bound']}`
  (cells 37 and 46), so they cover at most {d1['controlled_step_bound']} s.
- Each controlled run logs one row per vehicle per step, the same unit as the emission files. A pandas error in
  cell 48 prints both lengths: {_int(d1['rf_controlled_rows'])} rows (RF run) and {_int(d1['xgb_controlled_rows'])}
  rows (XGBoost run). These are {_pct(100 * d1['rf_row_ratio'])} and {_pct(100 * d1['xgb_row_ratio'])} of the
  baseline rows.
- By row count alone, the legacy "percentage drop" would be about {_pct(d1['rf_rowcount_implied_drop_pct'])} (RF)
  and {_pct(d1['xgb_rowcount_implied_drop_pct'])} (XGBoost). The reported NOx drops are {drops['RF']['NOx']:g}% and
  {drops['XGBoost']['NOx']:g}%. The ratio of horizons alone ({d1['controlled_step_bound']} s out of about
  {d1['baseline_t_max_mid_s']:,.0f} s) gives {_pct(d1['horizon_implied_drop_pct'])}.
- The first rows of all three files are identical (cell 55 output), as expected when the runs share a start state.
- What this means: the reported reductions have the size that the horizon mismatch alone produces. The emission
  XMLs of the controlled runs are not available, so this is supported-indirect. The M4 replication measures it.

### D2 No-op rerouting (row 3)

- The rerouting loop calls `traci.simulation.findRoute(current_edge, last_edge)` with default arguments, then
  `setRoute`, for every vehicle at every step whose predicted NOx exceeds 1.88.
- Cell outputs log every call:
  - RF run: {_int(rf['detections'])} detections and {_int(rf['reroute_calls'])} reroute calls across
    {_int(rf['vehicles'])} vehicles.
  - XGBoost run: {_int(xgb['detections'])} detections and {_int(xgb['reroute_calls'])} reroute calls across
    {_int(xgb['vehicles'])} vehicles.
- Every repeat call for a vehicle returned exactly the remaining part of the route the previous call gave it: RF
  {_int(rf['repeat_unchanged'])} of {_int(rf['repeat_calls'])}, XGBoost {_int(xgb['repeat_unchanged'])} of
  {_int(xgb['repeat_calls'])}. Internal `:` edges were ignored in this comparison.
- The first call per vehicle cannot be compared with the original route, which was never logged. Default
  `findRoute` without weights uses free-flow travel times, the same metric the original routes were most likely
  built with.
- What this means: once a vehicle had been "rerouted", further calls changed nothing. Whether the first call
  changed anything is decided by the replication's `route_change_rate`.
- The two controlled runs nevertheless diverge: the row counts differ, and the first new route is identical for
  only {same_first} of the {common} vehicles rerouted in both runs. So either the `setRoute` calls were not
  behaviour-neutral or the runs differed in settings. The replication checks the former.

### D4 Circular, leaky prediction task (row 5)

- The eight-model comparison (cell 18) predicts NOx from {d4['model_compare_features']} with
  `{d4['split']}`. It uses the raw `df`: `normalized_df` (cell 12) is not used in any later cell.
- Reported test MSEs come from this 6-feature comparison: RF {mse['Random Forest']['test_mse']:g}, XGBoost
  {mse['XGBoost']['test_mse']:g}, neural network {mse['Neural Network']['test_mse']:g}.
- The RF actually deployed for rerouting is a different model: cell 30, features {d4['rf_reroute_model_features']},
  test MSE {d4['rf_reroute_model_cell_30_test_mse']:.6f}. The report does not give this number. The deployed
  XGBoost (cell 45) uses {d4['xgb_reroute_model_features']}, MSE {d4['xgb_reroute_model_cell_45_test_mse']:.6f}.
- NOx and the input pollutants are outputs of the same emission model for the same vehicle and second. A random
  row split puts neighbouring seconds of the same vehicle into both training and test data. The small MSE therefore
  measures how nearly deterministic the emission model is, not the ability to forecast hotspots. The replication
  tests this with a single-feature monotone baseline and a split by run.

### D6 Threshold (row 7)

- Notebook: {"; ".join(f"cell {h['cell']}: `{h['text']}`" for h in d6['notebook_lines'])}.
- Report: 1.88 "grams per mile" on PDF pages {", ".join(map(str, d6['report_g_per_mile_pages']))}. Slides: PDF pages
  {", ".join(map(str, d6['slides_g_per_mile_pages'])) or "none found by the text search"}.
- The value is compared with the model's prediction of the `NOx` attribute of SUMO's emission output. That
  attribute is a per-vehicle rate for the current step, which `docs/SUMO_API_NOTES.md` checks on the installed SUMO.
- A rate per second, a concentration (ppm or µg/m³) and a distance-specific factor (g/mile) are three different
  quantities. No source for 1.88 in any of them is given.

### D7 Placeholders, paths and the data-collection loop (row 8)

- Hard-coded values presented as results:
  - "replace with actual values": {_hits(d7['replace_with_actual'])}.
  - Invented example values: {_hits(d7['example_values'])}. The "real map" in cell 57 shows percentage drops of
    0, 15 and 25 and NOx values of 1.5, 2.3 and 1.9 that no computation produced.
- Absolute `D:\\` paths: {_hits(d7['hardcoded_drive_paths'])}.
- The cell 2 loop `while step < {d7['collect_loop']['step_bound']}` never increments `step`
  (increments found: {d7['collect_loop']['increments_step']}). The cell 4 sample confirms it: rows
  {", ".join(veh0_rows)} are vehicle veh0 at successive positions, all with Step = 0. The loop can only have ended
  through an exception or a manual interrupt; cell 2 has no saved output, so the notebook does not record which.
  The loop logs only CO2, speed and position; the other pollutants used later come from `emissions_data.xml`.
- The slides (PDF page {", ".join(map(str, d7['slides_template_text_pages']))}) still carry template text.
- Cells with errors in the saved notebook: {"; ".join(f"cell {k}: {v[0]}" for k, v in d7['errors'].items())}.

### D8 References (row 9)

The report's reference list (PDF page {d8['report_reference_page'][0]}) and the slides' citation (PDF page
{d8['slides_citation_pages'][0]}, "Dong & Javid et al. (2022)") were checked against Crossref, arXiv and a web
search. The report's text also carries source tags "(MDPI)" and "(SpringerLink)" (PDF page
{", ".join(map(str, d8['source_tags_in_text_pages']))}). Details and the queries are in `docs/CITATION_LEDGER.md`.
No legacy reference is reused.

## 4. What the new design changes

| Defect | Remedy | Where |
|---|---|---|
| D1 | Every condition runs until all vehicles arrive (cap 14,400 s); validity rules; the legacy metric is computed next to the matched one as a demonstration | docs/SPECIFICATION.md 4.4, 7.4; test 9.9 |
| D2 | Efforts on every non-internal edge, `rerouteEffort`, route-change rate reported for every controller | 4.3, 4.5 |
| D3 | C0, C1, C2 (placebo) and C3 alongside the proposed C4 | 4.3 |
| D4 | Forecast the next window from traffic-only features; split by seed; persistence and historical baselines | 7.1-7.3 |
| D5 | 30-60 paired seeds, BCa CIs, Wilcoxon and TOST with Holm correction | 4.6, 4.7 |
| D6 | Threshold expressed as a training quantile, plus the literal value in mg/s | 7.4 |
| D7 | No hand-typed numbers; all figures from results; relative paths; hygiene test | P1, P6, 9.10 |
| D8 | Citation ledger with primary-source verification | 9.10, `docs/CITATION_LEDGER.md` |

{_replication_section()}"""
    out = docs_dir() / "LEGACY_AUDIT.md"
    out.write_text(text, encoding="utf-8")
    return rel(out)
