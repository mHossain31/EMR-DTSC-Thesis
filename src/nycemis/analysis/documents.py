"""Render documents whose numbers come from results files (docs/SPECIFICATION.md P1): the pilot report, the interim note and
the preregistration. The prose is fixed here; every number is read from JSON/YAML produced by code.
"""

from __future__ import annotations

import json
from datetime import date

from nycemis.config import base_config, load_yaml
from nycemis.legacy.replicate import d1_confirmed, mean_change_rate
from nycemis.manifest import load_manifest
from nycemis.paths import configs_dir, docs_dir, rel, repo_root, results_dir

LABELS = {"static": "C0 static", "tt_adaptive": "C1 tt_adaptive", "random_reroute": "C2 random_reroute",
          "eco_reactive": "C3 eco_reactive (alpha 0.5)", "eco_reactive_a0": "C3 eco_reactive (alpha 0)",
          "legacy_ml": "C5 legacy_ml (quantile threshold)", "legacy_ml_literal": "C5 legacy_ml (1.88 mg/s)"}


def _load(path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _pilot() -> dict:
    return _load(results_dir() / "pilot" / "pilot_summary.json")


def _effect_rows(p: dict, metric: str) -> list[str]:
    rows = []
    for key, v in p["paired_deltas"].items():
        a, b_metric_level = key.split(" vs ", 1)
        b, m, level = (x.strip() for x in b_metric_level.split("|"))
        if m != metric or b != "static":
            continue
        rows.append(f"| {LABELS.get(a, a)} | {level} | {v['n']} | {v['mean_pct']:+.2f} | "
                    f"{v['min_pct']:+.2f} to {v['max_pct']:+.2f} | {v['sd_pct']:.2f} |")
    return rows


def render_pilot_report() -> str:
    p = _pilot()
    rep = _load(results_dir() / "legacy_audit" / "replication.json")
    pw, bud = p["power"], p["budget"]
    lines = [
        "# Pilot report (M4, interim, not confirmatory)", "",
        "Generated by `python -m nycemis analyze-pilot`; do not edit by hand. Flushing, pilot seeds, three demand "
        f"levels; {p['runs_done']} of {p['planned']} runs done.", "",
        "## Total NOx relative to C0 static (paired by seed; valid pairs only)", "",
        "| Condition | Level | Pairs | Mean change % | Range % | SD % |", "|---|---|---|---|---|---|",
        *_effect_rows(p, "total_nox_g"), "",
        "## Mean travel time relative to C0 static", "",
        "| Condition | Level | Pairs | Mean change % | Range % | SD % |", "|---|---|---|---|---|---|",
        *_effect_rows(p, "mean_tt_s"), "",
        "## Validity", "", "| Condition | Level | Valid / runs |", "|---|---|---|",
    ]
    lines += [f"| {LABELS.get(v['label'], v['label'])} | {v['level']} | {v['valid']} / {v['runs']} |"
              for v in p["validity"]]
    lines += ["", "## alpha = 0 sanity (eco_reactive with alpha 0 vs tt_adaptive, mean travel time)", "",
              "| Level | eco_reactive alpha 0 (s) | tt_adaptive (s) | Relative difference | Within 5% |",
              "|---|---|---|---|---|"]
    lines += [f"| {lv} | {v['eco_reactive_a0_mean_tt_s']:.1f} | {v['tt_adaptive_mean_tt_s']:.1f} | "
              f"{100 * v['rel_diff']:+.2f}% | {v['within_5pct']} |" for lv, v in p["alpha0_sanity"].items()]
    lines += ["", "## Reconciliation", "",
              f"Largest |per-step NOx - tripinfo NOx| / tripinfo NOx over the pilot runs: {100 * p['recon_max_abs']:.3f}% "
              f"(tolerance 0.5%, DEVIATIONS #9): {'within' if p['recon_within_pilot_tolerance'] else 'OUTSIDE'}.",
              "", "## Power and sample size", "",
              f"- SD of paired NOx changes used: {pw['sd_pct_used']:.3f}% (the largest over the pilot comparisons "
              "and levels).",
              f"- Alpha per test: {pw['alpha_adjusted']:.5f} (0.05 / 12); SESOI {pw['sesoi_pct']:.1f}%.",
              f"- n for 80% power: superiority {pw['n_superiority']}, equivalence (TOST) {pw['n_equivalence']}; "
              f"n_power = {pw['n_power']}; confirmatory n = max(30, ceil(1.2 n_power)) capped at 60 = "
              f"**{pw['n_confirmatory']}**.", "",
              "## Budget for M5 and M6", "",
              "| Block | Runs | Median s per run | Core-hours |", "|---|---|---|---|"]
    lines += [f"| {k} | {v['runs']} | {v['median_s_per_run']:.0f} | {v['core_hours']:.1f} |"
              for k, v in bud["plan"].items()]
    lines += ["", f"Total {bud['total_core_hours']:.1f} core-hours; {bud['wall_clock_hours']:.1f} h wall-clock at "
              f"{bud['workers']} workers (limit 24 h: {'within' if bud['wall_clock_hours'] <= 24 else 'EXCEEDED'}). "
              f"Disk estimate {bud['disk_gb_estimate']:.1f} GB of {bud['free_disk_gb']:.0f} GB free.", "",
              "Median core-seconds per run (CPU time where recorded, else wall-clock): " + ", ".join(
                  f"{LABELS.get(k, k)} {v:.0f}" for k, v in sorted(bud["median_core_s_by_condition"].items())), "",
              "## Legacy-protocol replication", "",
              f"D1 horizon artifact {'reproduced' if d1_confirmed(rep) else 'not reproduced'}; the legacy rule changed "
              f"{100 * mean_change_rate(rep):.1f}% of the routes it recomputed. Details: `docs/LEGACY_AUDIT.md`, "
              "section 5.", ""]
    text = "\n".join(lines)
    (results_dir() / "pilot" / "pilot_report.md").write_text(text, encoding="utf-8")
    return rel(results_dir() / "pilot" / "pilot_report.md")


def render_interim_note() -> str:
    a = _load(results_dir() / "legacy_audit" / "audit_numbers.json")
    rep = _load(results_dir() / "legacy_audit" / "replication.json")
    p = _pilot()
    d1, d2 = a["d1_horizon"], a["d2_reroutes"]
    drops = d1["reported_drops_pct"]
    s_lq = {k.split("/")[1]: v for k, v in rep["summary"].items() if k.startswith("legacy_ml/")}

    def eff(label: str, metric: str) -> str:
        parts = []
        for lv in ("light", "moderate", "heavy"):
            v = p["paired_deltas"].get(f"{label} vs static | {metric} | {lv}")
            if v:
                parts.append(f"{lv} {v['mean_pct']:+.1f}% ({v['min_pct']:+.1f} to {v['max_pct']:+.1f})")
        return "; ".join(parts)

    lines = [
        "# Interim note: audit of the 2024 SUMO + ML project and pilot results",
        "",
        f"**Interim and non-confirmatory.** Written {date.today().isoformat()} from "
        "`results/legacy_audit/` and `results/pilot/`. The confirmatory study is preregistered and has not run yet; "
        "nothing below is a confirmatory result. All quantities are simulated tailpipe emissions in SUMO, not air "
        "quality or exposure.",
        "",
        "## What the original project reported",
        "",
        f"The 2024 project (NYIT DTSC 870; Hossain and Kyaw, supervised by Prof. X. Huang) reported that ML-triggered "
        f"rerouting in a SUMO model of Flushing reduced NOx by {drops['RF']['NOx']:g}% (random forest) and "
        f"{drops['XGBoost']['NOx']:g}% (XGBoost).",
        "",
        "## What the audit found (from the original notebook's saved outputs)",
        "",
        f"- **Unmatched horizons.** The baseline emissions file spans about {d1['baseline_t_max_mid_s']:,.0f} s of "
        f"simulation; the rerouting runs stopped after {d1['controlled_step_bound']} steps. Summing all records of "
        f"each file therefore compares {100 * d1['rf_row_ratio']:.1f}% (RF) and {100 * d1['xgb_row_ratio']:.1f}% "
        "(XGBoost) as many vehicle-steps with the full baseline, which by itself produces a drop of the reported "
        "size.",
        f"- **Rerouting that did not reroute.** {d2['rf']['repeat_unchanged']:,} of {d2['rf']['repeat_calls']:,} "
        "repeated reroute calls in the RF run returned the vehicle's unchanged route; the call was SUMO's default "
        "route search without traffic information (free-flow travel times).",
        "- **A circular prediction task.** NOx was predicted from CO2, CO, HC and PMx emitted by the same vehicle "
        "in the same second by the same emission model, with a random row split; the tiny errors measure the "
        "emission model, not forecasting skill.",
        "- **No controls and one run.** There was no matched no-rerouting run, no placebo and no repeated seeds; "
        "the threshold (1.88) was labelled ppm, bpm and g/mile in different places while it was compared with a "
        "rate in mg/s; some plotted values and percentages were typed in by hand; the four cited references "
        "could not be found.",
        "",
        "## Replication under a matched protocol (pilot: 5 seeds x 3 demand levels, Flushing)",
        "",
    ]
    for lv in ("light", "moderate", "heavy"):
        v = s_lq.get(lv)
        if v:
            lines.append(f"- {lv}: the legacy metric reports a {v['legacy_metric_drop_pct_mean']:.1f}% NOx drop "
                         f"(range {v['legacy_metric_drop_pct_min']:.1f} to {v['legacy_metric_drop_pct_max']:.1f}%); "
                         f"the matched metric reports {v['matched_drop_pct_mean']:+.2f}% "
                         f"({v['matched_drop_pct_min']:+.2f} to {v['matched_drop_pct_max']:+.2f}%).")
    lines += [
        f"- The legacy rule changed {100 * mean_change_rate(rep):.1f}% of the routes it recomputed.",
        "",
        "## Pilot effects of the new controllers (exploratory, 5 seeds, change in total NOx vs no rerouting)",
        "",
        f"- Travel-time rerouting (SUMO's rerouting device): {eff('tt_adaptive', 'total_nox_g')}.",
        f"- Measured-emission rerouting (alpha 0.5): {eff('eco_reactive', 'total_nox_g')}.",
        f"- Random-rerouting placebo: {eff('random_reroute', 'total_nox_g')}.",
        f"- Change in mean travel time, measured-emission rerouting: {eff('eco_reactive', 'mean_tt_s')}.",
        "",
        f"These pilot numbers size the confirmatory study: {p['power']['n_confirmatory']} paired seeds per "
        "condition and demand level, preregistered before the test seeds are run.",
        "",
        "## Limitations",
        "",
        "Synthetic demand not calibrated to traffic counts; HBEFA 4.2 emission factors based on European vehicles; "
        "no dispersion or weather (emissions are not concentrations); OSM-derived network; full driver compliance.",
        "",
    ]
    out = repo_root() / "application" / "interim_note.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    return rel(out)


def render_preregistration(stage: str, frozen: dict | None = None) -> str:
    """``stage`` is "draft (M4)" or "frozen (M6)"; ``frozen`` holds the M5/M6 values (alpha*, eta, model id, tag)."""
    cfg = base_config()
    p = _pilot()
    levels = load_yaml(configs_dir() / "demand_levels.yaml")["scenarios"]["flushing"]
    man = load_manifest()["files"]
    fz = frozen or {}
    n = p["power"]["n_confirmatory"]
    test = cfg.seeds.test_seeds(n)

    def f(key: str, default: str = "fixed at M5 (validation seeds)") -> str:
        return str(fz.get(key, default))

    lines = [
        "# Preregistration: forecast-driven emission-aware rerouting in a SUMO model of Flushing, Queens", "",
        f"- Status: **{stage}**; generated by `python -m nycemis prereg`; do not edit by hand.",
        f"- Date: {fz.get('date', date.today().isoformat())}; git commit {fz.get('commit', 'at the prereg-v1 tag')}; "
        f"tag {fz.get('tag', 'prereg-v1 (not yet created)')}.", "",
        "## Research questions", "",
        "RQ1 measurement validity; RQ2 forecasting; RQ3 control; RQ4 value of prediction (Tier 2); RQ5 side effects "
        "(docs/SPECIFICATION.md 4.1).", "",
        "## Confirmatory comparisons (Flushing; each at light, moderate, heavy demand)", "",
        f"SESOI {cfg.analysis.sesoi_pct:.0f}% of the reference total NOx. Outcome: total NOx (g) from tripinfo, paired by "
        "seed, delta% = 100 (Y_cond - Y_ref) / Y_ref.", "",
        "| ID | Comparison | Test | Hypothesis |", "|---|---|---|---|",
        "| PC1 | legacy_ml vs static | TOST, two one-sided paired Wilcoxon tests, margin +-2% | equivalence (near zero "
        "under the matched protocol) |",
        "| PC2 | eco_ml vs static | two-sided paired Wilcoxon | difference in total NOx |",
        "| PC3 | eco_ml vs tt_adaptive | two-sided paired Wilcoxon | difference in total NOx |",
        "| PC4 | eco_ml vs eco_reactive | TOST, margin +-2% | equivalence (does forecasting add value?) |", "",
        f"Multiplicity: one Holm family over the {cfg.analysis.n_confirmatory_tests} tests, familywise alpha "
        f"{cfg.analysis.familywise_alpha}. Equivalence is declared only if the Holm-adjusted TOST p-value is below "
        "0.05. Reported for every test: mean and median delta%, 95% BCa CI (10,000 resamples, seed "
        f"{cfg.analysis.bootstrap_seed}), unadjusted and Holm-adjusted p-values, d_z; for TOST also the 90% CI.", "",
        "## Conditions and parameters", "",
        "| Condition | Parameters |", "|---|---|",
        "| C0 static | free-flow routes from the route file |",
        "| C1 tt_adaptive | rerouting device, probability 1, period 60 s, adaptation interval 10 s, 18 steps |",
        f"| C2 random_reroute | eta = {f('eta')} (route-change rate matched to C4 on validation seeds) |",
        f"| C3 eco_reactive | alpha* = {f('alpha_reactive')}; EMA 0.5; shrinkage vs/(vs+30) |",
        f"| C4 eco_ml | alpha* = {f('alpha_ml')}; model {f('model_id')} (SHA-256 {f('model_sha256', 'at freeze')}) |",
        "| C5 legacy_ml | legacy RF, threshold at the legacy flag-share quantile of training NOx |", "",
        "Alpha* rule: minimise mean total NOx subject to mean travel time <= +5% over tt_adaptive, on validation seeds, "
        "chosen separately for C3 and C4. Reroute period 60 s per vehicle (staggered), compliance 100%.", "",
        "## Scenario, network, demand", "",
    ]
    for key in ("data/osm/flushing.osm.xml.gz", "scenarios/flushing/flushing.net.xml.gz"):
        if key in man:
            lines.append(f"- `{key}`: SHA-256 `{man[key]['sha256']}`")
    lines += ["- Demand levels (veh/h/km): " + ", ".join(
        f"{k} {v['density_per_h_km']:g} (relative speed ratio {v['achieved_relative_speed_ratio']:.3f})"
        for k, v in levels["levels"].items()),
        f"- Test seeds: {test[0]}-{test[-1]} (n = {n}); pilot {cfg.seeds.pilot[0]}-{cfg.seeds.pilot[1]}, train "
        f"{cfg.seeds.train[0]}-{cfg.seeds.train[1]}, validation {cfg.seeds.validation[0]}-{cfg.seeds.validation[1]}.",
        "", "## Protocol and validity", "",
        f"Step {cfg.protocol.step_length_s:g} s; departures {cfg.protocol.depart_begin_s}-{cfg.protocol.depart_end_s} s; run "
        f"until every vehicle arrives (cap {cfg.protocol.cap_s} s); time-to-teleport {cfg.protocol.time_to_teleport_s} s; "
        f"ignore-junction-blocker {cfg.protocol.ignore_junction_blocker_s} s; collisions warn. Valid run: completion >= "
        f"{100 * cfg.protocol.validity.completion_min:.1f}%, teleports <= {100 * cfg.protocol.validity.teleport_max_frac:.1f}% "
        "of trips, no crash or timeout. Confirmatory tests use pairs where both runs are valid; a sensitivity "
        "analysis uses all pairs. Invalid-run counts are reported per condition.", "",
        "## Metrics", "",
        "Primary: total NOx (g) = sum of tripinfo NOx_abs (mg) / 1000. Secondary: total CO2 (kg), NOx per vehicle-km, "
        "mean and 95th-percentile travel time, time loss, waiting time, vehicle-km, departure delay, reroutes and "
        "route-change rate, controller time per tick, teleports, collisions, completion. Spatial (RQ5): NOx share by "
        "road class, p99 5-minute edge NOx density, Gini of per-edge NOx.", "",
        "## Sample size", "",
        f"Pilot SD of paired NOx changes {p['power']['sd_pct_used']:.3f}% (largest over comparisons and levels); "
        f"alpha per test {p['power']['alpha_adjusted']:.5f}; 80% power needs n = {p['power']['n_superiority']} "
        f"(superiority at 2%) and {p['power']['n_equivalence']} (TOST at +-2%, true effect 0); confirmatory n = "
        f"{n}.", "",
        "## Exploratory (not confirmatory)", "",
        "Everything except PC1-PC4: secondary metrics, CO2, RQ5 side effects, Pareto curves over alpha, forecast "
        "skill, the literal-threshold legacy variant, the travel-time effects, Tier 2.", "",
        "## Deviations policy", "",
        "Any change after the tag is logged in `docs/DEVIATIONS.md` with the reason; affected analyses are re-run "
        "and both versions reported.", "",
        "## Known limitations", "",
        "See `docs/LIMITATIONS.md` (synthetic demand, European emission factors, no dispersion, OSM network, full "
        "compliance, single-hour profile, no field validation).", "",
    ]
    out = docs_dir() / "PREREGISTRATION.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return rel(out)


def render_faq() -> str:
    """Interview FAQ (docs/SPECIFICATION.md M9). Results-dependent answers are added only once their result files exist."""
    a = _load(results_dir() / "legacy_audit" / "audit_numbers.json")
    d1, d2 = a["d1_horizon"], a["d2_reroutes"]
    rep_path = results_dir() / "legacy_audit" / "replication.json"
    lines = [
        "# Interview FAQ", "",
        "Generated by `python -m nycemis paper`; numbers come from `results/`. Answers about the confirmatory "
        "results appear only after the confirmatory analysis has run.", "",
        "## What was wrong with version 1, and how did you find out?", "",
        "I reread the original notebook's saved outputs line by line before rebuilding anything. Three things stood "
        "out. First, the baseline emissions file covered about "
        f"{d1['baseline_t_max_mid_s']:,.0f} s of simulation, but the rerouting runs were stopped after "
        f"{d1['controlled_step_bound']} steps; summing every record of each file compared "
        f"{100 * d1['rf_row_ratio']:.1f}% as many vehicle-steps against the full baseline, which alone produces a "
        f"drop of the reported size ({d1['reported_drops_pct']['RF']['NOx']:g}% NOx). Second, the rerouting call "
        "was SUMO's default route search with no traffic information (free-flow travel times); "
        f"{d2['rf']['repeat_unchanged']:,} of {d2['rf']['repeat_calls']:,} repeated calls returned the unchanged "
        "route, and on our networks the same call reproduces the free-flow routes vehicles are generated with. "
        "Third, the model predicted "
        "NOx from other pollutants emitted by the same vehicle in the same second, with a random row split, so its "
        "tiny error measured the emission model, not forecasting.",
    ]
    if rep_path.is_file():
        rep = _load(rep_path)
        s = {k.split("/")[1]: v for k, v in rep["summary"].items() if k.startswith("legacy_ml/")}
        if "moderate" in s:
            v = s["moderate"]
            lines += ["", "I then replicated the legacy rule under a matched protocol: at moderate demand the "
                      f"legacy metric reports a {v['legacy_metric_drop_pct_mean']:.1f}% drop, the matched metric "
                      f"{v['matched_drop_pct_mean']:+.2f}%."]
    lines += [
        "", "## Why a simulation, and what can it not tell you?", "",
        "Rerouting experiments cannot be randomised on real streets, and simulation lets every condition share the "
        "same demand and seed. The price: synthetic demand not calibrated to counts, European emission factors, no "
        "dispersion (emissions are not concentrations or exposure), an OpenStreetMap network and fully compliant "
        "drivers. Every claim is about simulated tailpipe emissions.", "",
        "## Why preregister a simulation study?", "",
        "Simulations make it cheap to try many settings and report the best one. Fixing the comparisons, the alpha "
        "selection rule, the seeds, the sample size and the analysis code by git tag before the test seeds ran "
        "removes that freedom.", "",
        "## Why forecast from traffic state only?", "",
        "A controller deployed on real streets would see counts and speeds, not each vehicle's tailpipe. The "
        "forecaster therefore uses traffic features only; a variant with lagged emissions is an ablation.", "",
        "## What did you do about the original references?", "",
        "None of the four could be found; three of their volume and article numbers point to unrelated papers. "
        "No legacy reference is reused, and every citation in the new paper is checked and logged with the claim it "
        "supports (docs/CITATION_LEDGER.md).", "",
    ]
    c = results_dir() / "confirmatory" / "analysis.json"
    if c.is_file():
        from nycemis.analysis.claims import confirmatory_sentence

        res = _load(c)
        lines += ["## What did the preregistered comparisons show?", ""]
        lines += [f"- {confirmatory_sentence(r)}" for r in res["confirmatory"]]
        lines.append("")
    out = repo_root() / "application" / "interview_faq.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rel(out)
