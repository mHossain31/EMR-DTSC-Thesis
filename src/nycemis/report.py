def _network_facts(scenario: str) -> dict:
    from collections import Counter

    import sumolib

    from nycemis.network.build import net_path
    from nycemis.sim.netinfo import road_class

    net = sumolib.net.readNet(str(net_path(scenario)), withInternal=False)
    km: dict[str, Counter] = {}
    lane_km = 0.0
    for e in net.getEdges():
        lk = e.getLength() * e.getLaneNumber() / 1000.0
        lane_km += lk
        km.setdefault(road_class(e.getType()), Counter())[round(e.getSpeed() * 3.6)] += lk
    nodes = Counter(n.getType() for n in net.getNodes())

    def modal(cls: str) -> str:
        speed, k = km[cls].most_common(1)[0]
        return f"{speed} ({100 * k / sum(km[cls].values()):.0f}\\%)"

    return {"edges": _num(len(net.getEdges())), "lane_km": _num(lane_km, 0),
            "signals": _num(len(net.getTrafficLights())), "priority": _num(nodes.get("priority", 0)),
            "stop": _num(nodes.get("allway_stop", 0) + nodes.get("priority_stop", 0)),
            "primsec": modal("primary/secondary"), "tertiary": modal("tertiary"), "resid": modal(RESID)}


