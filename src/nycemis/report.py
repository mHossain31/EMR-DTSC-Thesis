def write_typeset_macros() -> str:
    """``paper/macros_typeset.tex``: every generated macro whose value holds a negative number, redefined with a
    typographic minus ($-$) instead of a hyphen. Derived mechanically from the two generated macro files, so no value
    is retyped; the paper versions input it after them."""
    import re

    sign = re.compile(r"(?<![\w\-])-(?=\d)")
    out = ["% Generated by `python -m nycemis report` from macros.tex and macros_sensitivity.tex; do not edit."]
    for name in ("macros.tex", "macros_sensitivity.tex"):
        for key, val in re.findall(r"^\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}$", (PAPER / name).read_text(encoding="utf-8"),
                                   flags=re.MULTILINE):
            new = sign.sub("$-$", val)
            if new != val:
                out.append(rf"\renewcommand{{\{key}}}{{{new}}}")
    path = PAPER / "macros_typeset.tex"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return rel(path)


