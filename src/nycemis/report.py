def table_design() -> str:
    from nycemis.experiments.plan import exp_dir

    rows = []
    for exp, purpose in (("pilot", "Runtime, variance, power"), ("dataset", "Forecaster training data"),
                         ("validation", r"$\alpha^*$, $\eta^*$, tuning"), ("confirmatory", "PC1--PC4 (preregistered)"),
                         ("legacy_recount", "Route-change recount"), ("sensitivity_posted", "Street-coding sensitivity")):
        plan = _load(exp_dir(exp) / "plan.json")
        if not plan:
            continue
        seeds = sorted({r["spec"]["seed"] for r in plan["runs"]})
        labels = sorted({r["label"] for r in plan["runs"]})
        runs_of, start = [], seeds[0]
        for a, b in zip(seeds, [*seeds[1:], None], strict=True):
            if b != a + 1:
                runs_of.append(f"{start}--{a}" if a != start else f"{a}")
                start = b
        rng = ", ".join(runs_of)
        rows.append([exp.replace("_", r"\_"), rng, str(len(labels)), _num(len(plan["runs"])), purpose])
    return _write("tab_design", "llrrl", ["Experiment", "Seeds", "Conditions", "Runs", "Purpose"], rows)


