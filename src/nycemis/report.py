def _load(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def _pct(x: float, nd: int = 1) -> str:
    return f"{x:+.{nd}f}".replace("-", "$-$")


def _ci(lo: float, hi: float, nd: int = 1) -> str:
    return f"[{_pct(lo, nd)}, {_pct(hi, nd)}]"


def _p(p: float) -> str:
    if p < 1e-9:
        return r"$<10^{-9}$"
    if p < 1e-3:
        mant, exp = f"{p:.1e}".split("e")
        return rf"${mant}\times10^{{{int(exp)}}}$"
    return f"{p:.3f}"


def _num(x: float, nd: int = 0) -> str:
    return f"{x:,.{nd}f}"


def _write(name: str, cols: str, header: list[str], rows: list[list[str]], groups: list[int] | None = None,
           pre: list[str] | None = None) -> str:
    lines = [rf"\begin{{tabular}}{{{cols}}}", r"\toprule", *(pre or []), " & ".join(header) + r" \\", r"\midrule"]
    for i, r in enumerate(rows):
        if groups and i in groups and i > 0:
            lines.append(r"\addlinespace")
        lines.append(" & ".join(r) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    TABLES.mkdir(parents=True, exist_ok=True)
    path = TABLES / f"{name}.tex"
    path.write_text("% Generated by `python -m nycemis report` from result files; do not edit by hand.\n"
                    + "\n".join(lines) + "\n", encoding="utf-8")
    return rel(path)


