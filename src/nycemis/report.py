# ---------------------------------------------------------------- build

def tex_engine() -> str | None:
    local = repo_root() / "tools" / ("tectonic.exe" if os.name == "nt" else "tectonic")
    return str(local) if local.is_file() else shutil.which("tectonic")


def build(variant: str) -> str:
    """Compile ``paper/<variant>/main.tex`` with tectonic into ``paper/<variant>/build/main.pdf``."""
    engine = tex_engine()
    if engine is None:
        raise FileNotFoundError("no tectonic (tools/tectonic.exe or PATH)")
    src = PAPER / variant
    (src / "build").mkdir(exist_ok=True)
    env = {**os.environ}
    env.setdefault("TECTONIC_CACHE_DIR", (repo_root() / "tools" / "tectonic-cache").as_posix())
    proc = subprocess.run([engine, "-X", "compile", "main.tex", "--outdir", "build", "--keep-logs"], cwd=src, env=env,
                          capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"LaTeX build of {variant} failed:\n{(proc.stdout + proc.stderr)[-3000:]}")
    return rel(src / "build" / "main.pdf")


PDF_NAMES = {"journal": "journal_preprint.pdf", "ieee": "ieee_conference.pdf"}


def run_all() -> list[str]:
    """Tables, typeset macros, figures, then both paper versions; each PDF is also copied next to its source."""
    written = [*write_tables(), write_typeset_macros(), *write_figures()]
    for variant, name in PDF_NAMES.items():
        pdf = repo_root() / build(variant)
        shutil.copyfile(pdf, PAPER / variant / name)
        written += [rel(pdf), rel(PAPER / variant / name)]
    return written
