"""Freeze the confirmatory design (docs/SPECIFICATION.md M6, Appendix B).

Reads the M5 selection (``results/validation/selection.json``) and the pilot's sample size, then writes
``configs/experiments/confirmatory.yaml`` and the frozen ``docs/PREREGISTRATION.md``. The confirmatory conditions copy
the parameters of the selected validation conditions verbatim, so nothing is retyped. The analysis-code hash covers
the analysis package and the base configuration that holds the analysis constants.
"""

from __future__ import annotations

import hashlib
import json
from datetime import date

import yaml

from nycemis.experiments.plan import load_experiment
from nycemis.experiments.power import detectable_at, power_at
from nycemis.manifest import sha256_file
from nycemis.models.train import model_path
from nycemis.paths import configs_dir, rel, repo_root, results_dir

SCENARIO = "flushing"
LEVELS = ["light", "moderate", "heavy"]
RECONCILE_SAMPLE_FRAC = 0.05  # share of confirmatory runs that also carry the per-step reconciliation logger


def analysis_code_files() -> list:
    root = repo_root()
    files = sorted((root / "src" / "nycemis" / "analysis").glob("*.py"))
    return [*files, root / "configs" / "base.yaml"]


def text_sha256(path) -> str:
    """SHA-256 of a text file with CRLF read as LF: the repository stores LF (.gitattributes), while a Windows
    checkout may hold CRLF, and the hash must be the same in both."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def analysis_code_sha256() -> str:
    """SHA-256 over (relative path, file SHA-256) pairs, so a renamed or edited file changes the hash; line endings
    do not (``text_sha256``)."""
    h = hashlib.sha256()
    for p in analysis_code_files():
        h.update(f"{rel(p)}\0{text_sha256(p)}\n".encode())
    return h.hexdigest()


def _validation_params(controller: str, **match) -> dict:
    """Parameters of the one validation condition of ``controller`` whose parameters include ``match``; matched by
    value, not by label, so the label's number format does not matter."""
    hits = [dict(c.params) for c in load_experiment("validation").conditions
            if c.controller == controller and all(c.params.get(k) == v for k, v in match.items())]
    if len(hits) != 1:
        raise KeyError(f"expected one validation condition {controller} with {match}, found {len(hits)}")
    return hits[0]


def _flow(d: dict) -> str:
    return yaml.safe_dump(d, default_flow_style=True, sort_keys=False, width=200).strip()


def write_confirmatory(selection: dict, n: int) -> str:
    a_r = selection["eco_reactive"]["alpha_star"]
    a_ml = selection["eco_ml"]["alpha_star"]
    eta = selection["random_reroute"]["eta_star"]
    conditions = [
        {"controller": "static", "dataset": True},
        {"controller": "tt_adaptive"},
        {"controller": "random_reroute", "params": _validation_params("random_reroute", eta=eta)},
        {"controller": "eco_reactive", "params": _validation_params("eco_reactive", alpha=a_r)},
        {"controller": "eco_ml", "params": _validation_params("eco_ml", alpha=a_ml), "dataset": True},
        {"controller": "legacy_ml", "params": {"threshold_mg_s": "legacy_quantile", "model_id": "legacy_rf"}},
    ]
    lines = [
        "# Confirmatory experiment (docs/SPECIFICATION.md M6). Generated by `python -m nycemis prereg` from",
        "# results/validation/selection.json (alpha*, eta) and results/pilot/pilot_summary.json (n); do not edit by hand.",
        "# static and eco_ml also record the edge-window dataset, for the held-out forecast evaluation on test seeds.",
        "name: confirmatory",
        f"scenario: {SCENARIO}",
        f"levels: [{', '.join(LEVELS)}]",
        "seed_role: test",
        f"test_n: {n}",
        f"reconcile_sample_frac: {RECONCILE_SAMPLE_FRAC}",
        "conditions:",
        *[f"  - {_flow(c)}" for c in conditions],
        "",
    ]
    path = configs_dir() / "experiments" / "confirmatory.yaml"
    path.write_text("\n".join(lines), encoding="utf-8")
    load_experiment("confirmatory")  # schema check of what was just written
    return rel(path)


def freeze() -> dict:
    from nycemis.analysis.documents import render_preregistration

    sel = json.loads((results_dir() / "validation" / "selection.json").read_text(encoding="utf-8"))
    pilot = json.loads((results_dir() / "pilot" / "pilot_summary.json").read_text(encoding="utf-8"))
    n = int(pilot["power"]["n_confirmatory"])
    pw = pilot["power"]
    args = (n, pw["sd_pct_used"])
    sim = {"alpha": pw["alpha_adjusted"], "sims": pw["sims_per_n"], "seed": pw["seed"]}
    power_at_n = {
        "superiority": power_at("superiority", *args, pw["sesoi_pct"], **sim),
        "equivalence": power_at("equivalence", *args, pw["sesoi_pct"], **sim),
        "detectable_effect_pct": detectable_at("superiority", *args, **sim),
        "detectable_margin_pct": detectable_at("equivalence", *args, **sim),
    }
    a_ml = sel["eco_ml"]["alpha_star"]
    model_id = _validation_params("eco_ml", alpha=a_ml)["model_id"]
    mpath = model_path(SCENARIO, model_id)
    frozen = {
        "alpha_reactive": f"{sel['eco_reactive']['alpha_star']:g}",
        "alpha_ml": f"{a_ml:g}",
        "eta": f"{sel['random_reroute']['eta_star']:g}",
        "model_id": model_id,
        "model_sha256": sha256_file(mpath),
        "analysis_code_sha256": analysis_code_sha256(),
        "analysis_code_files": [rel(p) for p in analysis_code_files()],
        "date": date.today().isoformat(),
        "tag": "prereg-v1",
        "power_at_n": power_at_n,
    }
    cfg_path = write_confirmatory(sel, n)
    doc = render_preregistration("frozen (M6)", frozen=frozen)
    out = {**frozen, "n": n, "confirmatory_config": cfg_path, "preregistration": doc}
    path = results_dir() / "validation" / "prereg_freeze.json"
    path.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    return out
